export const MountLevelThresholds = [0, 250, 900, 2500];

export function getMountDefinition(id) {
  return MountDefinitions.find((m) => m.id === id) || null;
}

export function getMountLevelForXp(xp) {
  let level = 1;
  for (let i = 1; i < MountLevelThresholds.length; i++) {
    if (xp >= MountLevelThresholds[i]) level = [1, 5, 10, 20][i];
  }
  return level;
}

export function getMountStatMultiplier(level) {
  if (level >= 20) return 1.45;
  if (level >= 10) return 1.28;
  if (level >= 5) return 1.15;
  return 1.0;
}

